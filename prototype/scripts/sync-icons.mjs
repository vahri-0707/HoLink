import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, readdir, readFile, writeFile, copyFile, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';

const execute = promisify(execFile);
const root = fileURLToPath(new URL('../', import.meta.url));
const icons = {
  'layout-dashboard':'squares-four', 'chart-no-axes-column':'chart-bar', search:'magnifying-glass',
  'qr-code':'qr-code', contact:'identification-card', settings:'gear-six', headphones:'headset',
  folder:'folder-simple', 'grip-vertical':'dots-six-vertical', ellipsis:'dots-three',
  'external-link':'arrow-square-out', eye:'eye', 'arrow-up-right':'arrow-up-right', copy:'copy-simple',
  mail:'envelope-simple', user:'user-circle', bell:'bell', 'circle-check':'check-circle',
  plus:'plus', check:'check', x:'x', 'undo-2':'arrow-counter-clockwise',
  'chevron-left':'caret-left', 'chevron-right':'caret-right', 'chevron-down':'caret-down',
  'layout-grid':'grid-four', link:'link-simple', list:'list-bullets', sidebar:'sidebar-simple',
  'credit-card':'credit-card', help:'question', 'user-plus':'user-plus', 'arrow-right':'arrow-right',
  info:'info', circle:'circle',
  text:'text-aa', separator:'minus', image:'images', music:'music-notes', podcast:'microphone-stage',
  play:'play', video:'youtube-logo', file:'file-pdf', calendar:'calendar-dots',
  phone:'phone', whatsapp:'whatsapp-logo', location:'map-pin'
};
const staging = path.join(os.tmpdir(), 'holink-better-icons-phosphor');
await mkdir(staging, { recursive:true });
const manifest = {};
const jobs = Object.entries(icons).flatMap(([name, glyph]) => [false,true].map(filled => ({
  name, filled, id:`ph:${glyph}${filled?'-fill':''}`, filename:`${name}${filled?'-fill':''}.svg`
})));
const filenames=jobs.map(job=>job.filename);
let completed = 0;
async function worker() {
  for (;;) {
    const job = jobs.shift();
    if (!job) return;
    let result;
    try {
      const existing=JSON.parse(await readFile(path.join(root,'assets/icons/manifest.json'),'utf8'));
      if(existing.icons[job.name]?.[job.filled?'filled':'outline']!==job.id) throw Error('New glyph');
      result={id:job.id,svg:await readFile(path.join(root,'assets/icons',job.filename),'utf8')};
    } catch {
      const {stdout} = await execute('npx', ['--yes','better-icons','get',job.id,'--json'], {maxBuffer:1024*1024});
      result = JSON.parse(stdout.trim());
    }
    if (result.id !== job.id || !result.svg || !result.svg.includes('viewBox="0 0 256 256"')) throw new Error(`Invalid icon: ${job.id}`);
    if (/<script|<foreignObject|\bon\w+=|(?:href|src)=/i.test(result.svg)) throw new Error(`Unexpected SVG content: ${job.id}`);
    const svg = result.svg.replace(/width="1em"/,'width="24"').replace(/height="1em"/,'height="24"').trimEnd();
    await writeFile(path.join(staging,job.filename),svg+'\n');
    manifest[job.name] ||= {};
    manifest[job.name][job.filled?'filled':'outline'] = job.id;
    if (++completed % 14 === 0) console.log(`${completed} SVGs retrieved through better-icons`);
  }
}
await Promise.all(Array.from({length:6},worker));
const metadata = {
  family:'Phosphor', collection:'ph', source:'https://github.com/phosphor-icons/core',
  retrievedWith:'npx --yes better-icons get <icon-id> --json',
  outlineWeight:'Regular', selectedWeight:'Fill', viewBox:256,
  filledContexts:['sidebar','header','page-settings'],
  outlineDesignWeight:16, outlineWeightAt24px:1.5,
  note:'Phosphor Regular encodes its uniform stroke as filled outline paths. Do not mix Light, Thin or Bold into outline states.',
  icons:Object.fromEntries(Object.entries(manifest).sort(([a],[b])=>a.localeCompare(b)))
};
const destinations = [path.join(root,'assets/icons'),path.resolve(root,'../figma-design/assets/icons')];
for (const destination of destinations) {
  await mkdir(destination,{recursive:true});
  for (const filename of await readdir(destination)) if (filename.endsWith('.svg')) await unlink(path.join(destination,filename));
  for (const filename of filenames) await copyFile(path.join(staging,filename),path.join(destination,filename));
  await writeFile(path.join(destination,'manifest.json'),JSON.stringify(metadata,null,2)+'\n');
}
await writeFile(path.join(root,'src/icons.js'),`// Generated by scripts/sync-icons.mjs through better-icons.\nexport const ICONS = Object.freeze(${JSON.stringify(metadata.icons,null,2)});\nexport const ICON_FAMILY = 'Phosphor';\nexport const OUTLINE_WEIGHT = 'Regular';\n`);
console.log(`Saved ${completed} verified local SVGs in both project asset directories.`);
